export function findNavItem(pathname: string) {
  const flattened = navigation.flatMap((section) => section.items);
  if (pathname === "/") {
    return flattened.find((item) => item.href === "/");
  }

  return flattened
    .filter((item) => item.href !== "/" && pathname.startsWith(item.href))
    .sort((left, right) => right.href.length - left.href.length)[0];
}

export function getBreadcrumbs(pathname: string) {
  if (pathname === "/") {
    return [{ label: "Command Center" }];
  }

  if (pathname === "/foundation") {
    return [
      { label: "Command Center", href: "/" },
      { label: "Foundation" },
    ];
  }

  if (pathname === "/login") {
    return [{ label: "Sign in" }];
  }

  if (pathname === "/profile") {
    return [
      { label: "Command Center", href: "/" },
      { label: "Profile" },
    ];
  }

  if (pathname === "/unauthorized") {
    return [
      { label: "Command Center", href: "/" },
      { label: "Access denied" },
    ];
  }

  if (pathname.startsWith("/masters/")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Masters", href: "/masters/products" },
      { label: item?.label || "Record" },
    ];
  }

  if (pathname.startsWith("/warehouse")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Warehouse", href: "/warehouse" },
      ...(item && item.href !== "/warehouse" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/complaints")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Complaints & Market Feedback", href: "/complaints" },
      ...(item && item.href !== "/complaints" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/sq")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Supplier Quality", href: "/sq" },
      ...(item && item.href !== "/sq" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/pv")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Pharmacovigilance", href: "/pv" },
      ...(item && item.href !== "/pv" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/ra")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Regulatory Affairs", href: "/ra" },
      ...(item && item.href !== "/ra" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/qa")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Quality Assurance", href: "/qa" },
      ...(item && item.href !== "/qa" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/qc")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Quality Control", href: "/qc" },
      ...(item && item.href !== "/qc" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/production")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Production", href: "/production" },
      ...(item && item.href !== "/production" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/procurement")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Procurement", href: "/procurement" },
      ...(item && item.href !== "/procurement" ? [{ label: item.label }] : []),
    ];
  }

  if (pathname.startsWith("/admin/")) {
    const item = findNavItem(pathname);
    return [
      { label: "Command Center", href: "/" },
      { label: "Administration", href: "/admin/company" },
      { label: item?.label || "Master" },
    ];
  }

  const item = findNavItem(pathname);
  if (!item) {
    return [
      { label: "Command Center", href: "/" },
      { label: "Workspace" },
    ];
  }

  return [
    { label: "Command Center", href: "/" },
    { label: item.label },
  ];
}
