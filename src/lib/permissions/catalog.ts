import { PERMISSION_ACTIONS, PERMISSION_MODULES } from "@/types/permissions";

function allActions(module: PermissionModule): Permission[] {
  return PERMISSION_ACTIONS.map((action) => `${module}:${action}` as Permission);
}

function actions(
  module: PermissionModule,
  selected: Array<(typeof PERMISSION_ACTIONS)[number]>
): Permission[] {
  return selected.map((action) => `${module}:${action}` as Permission);
}

function read(module: PermissionModule): Permission[] {
  return actions(module, ["read"]);
}

